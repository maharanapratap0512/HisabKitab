#!/usr/bin/env node
// bin/sutramcore.js — sutramcore CLI
'use strict';

const fs   = require('fs');
const path = require('path');

const [,, command, ...argv] = process.argv;

const COMMANDS = {
    init:   cmdInit,
    import: cmdImport,
};

if (!command || !COMMANDS[command]) {
    console.log(`
sutramcore — सूत्र CLI

Usage:
  npx sutramcore <command> [options]

Commands:
  init                             Create starter database/ folder with schema.js, migrations.js, views.js
  import <path/to/file.db>        Read a SQLite .db file and generate schema.js
    --out <dir>                    Output directory (default: ./database)
    --force                        Overwrite schema.js if it already exists

Examples:
  npx sutramcore init
  npx sutramcore import ./data/app.db
  npx sutramcore import ./data/app.db --out ./database
  npx sutramcore import ./data/app.db --out ./database/test --force
`);
    process.exit(0);
}

COMMANDS[command]();

// ─── import ──────────────────────────────────────────────────────────────────

function cmdImport() {
    const dbPath  = argv[0];
    const outIdx  = argv.indexOf('--out');
    const outDir  = outIdx !== -1 ? argv[outIdx + 1] : './database';
    const force   = argv.includes('--force');

    if (!dbPath) {
        console.error('[sutramcore] import: missing <path/to/file.db>\n');
        console.error('  Usage: npx sutramcore import <path/to/file.db> [--out <dir>] [--force]');
        process.exit(1);
    }

    const resolvedDb  = path.resolve(process.cwd(), dbPath);
    const resolvedOut = path.resolve(process.cwd(), outDir);

    if (!fs.existsSync(resolvedDb)) {
        console.error(`[sutramcore] File not found: ${resolvedDb}`);
        process.exit(1);
    }

    // load better-sqlite3
    let Database;
    try {
        Database = require(require.resolve('better-sqlite3', { paths: [process.cwd()] }));
    } catch {
        console.error('[sutramcore] better-sqlite3 is required for import.');
        console.error('  Run: npm install better-sqlite3');
        process.exit(1);
    }

    // open db read-only
    let db;
    try {
        db = new Database(resolvedDb, { readonly: true });
    } catch (err) {
        console.error(`[sutramcore] Could not open database: ${err.message}`);
        process.exit(1);
    }

    // read tables — skip sqlite_ internals and sys_ engine tables
    const tables = db.prepare(`
        SELECT name FROM sqlite_master
        WHERE type = 'table'
        AND name NOT LIKE 'sqlite_%'
        AND name NOT LIKE 'sys_%'
        ORDER BY name
    `).all();

    if (tables.length === 0) {
        console.warn('[sutramcore] No user tables found in the database.');
        console.warn('  (sys_ and sqlite_ tables are skipped automatically)');
        db.close();
        process.exit(0);
    }

    // read FK info for all tables
    const fkMap = {};
    for (const { name } of tables) {
        fkMap[name] = {};
        const fks = db.prepare(`PRAGMA foreign_key_list("${name}")`).all();
        for (const fk of fks) {
            fkMap[name][fk.from] = { table: fk.table, to: fk.to };
        }
    }

    // read columns for all tables
    const tableColumns = {};
    for (const { name } of tables) {
        tableColumns[name] = db.prepare(`PRAGMA table_info("${name}")`).all();
    }

    db.close();

    // generate schema.js
    const lines = [];
    lines.push(`// database/schema.js`);
    lines.push(`// Auto-generated by: npx sutramcore import ${dbPath}`);
    lines.push(`// Review: add joins{} (hasMany / manyToMany) manually`);
    lines.push(`'use strict';`);
    lines.push(``);
    lines.push(`const { defineTable, col } = require('sutramcore');`);
    lines.push(``);
    lines.push(`module.exports = {`);
    lines.push(``);

    for (const { name: tableName } of tables) {
        const columns = tableColumns[tableName];
        const fks     = fkMap[tableName];

        lines.push(`  ...defineTable('${tableName}', {`);

        const maxLen = Math.max(...columns.map(c => c.name.length));

        for (const c of columns) {
            const padded = c.name.padEnd(maxLen);
            const fk     = fks[c.name];
            let   colStr;

            if (fk) {
                // detect label column on ref table
                const refCols   = tableColumns[fk.table] ?? [];
                const labelCol  = detectLabelCol(refCols, fk.table);
                const selectStr = labelCol ? `['${labelCol}']` : `'*'`;
                colStr = `col.ref('${fk.table}.${fk.to}', { as: '${fk.table}', select: ${selectStr} })`;
            } else {
                colStr = buildColStr(c);
            }

            lines.push(`    ${padded} : ${colStr},`);
        }

        lines.push(`  }),`);
        lines.push(``);
    }

    lines.push(`};`);
    lines.push(``);

    const content = lines.join('\n');

    // write output
    if (!fs.existsSync(resolvedOut)) {
        fs.mkdirSync(resolvedOut, { recursive: true });
        console.log(`[sutramcore] Created ${outDir}/`);
    }

    const outFile = path.join(resolvedOut, 'schema.js');

    if (fs.existsSync(outFile) && !force) {
        console.error(`[sutramcore] schema.js already exists at ${outFile}`);
        console.error('  Use --force to overwrite.');
        process.exit(1);
    }

    fs.writeFileSync(outFile, content, 'utf8');

    console.log(`\n[sutramcore] ✓ Import complete`);
    console.log(`\n  Tables found : ${tables.length}`);
    console.log(`  Output       : ${outFile}`);
    console.log(`\nNext steps:`);
    console.log(`  1. Review schema.js — check col types, add .required() / .default() where needed`);
    console.log(`  2. Add joins{} manually for hasMany and manyToMany relationships`);
    console.log(`  3. col.ref() entries were auto-detected from foreign keys in the .db file\n`);
}

// detect label column — common name patterns
function detectLabelCol(cols, tableName) {
    const names = cols.map(c => c.name.toLowerCase());
    const candidates = [
        'name', 'title', 'label',
        tableName + '_name', tableName + '_hin', tableName + '_eng',
        'hin', 'eng', 'unit_short', 'short_name',
    ];
    for (const c of candidates) {
        if (names.includes(c)) return cols[names.indexOf(c)].name;
    }
    // fallback — first non-pk string column
    const strCol = cols.find(c => {
        const t = (c.type || '').toUpperCase();
        return c.pk !== 1 && (t.includes('TEXT') || t.includes('VARCHAR') || t.includes('CHAR') || t === '');
    });
    return strCol?.name ?? null;
}

// map SQLite column → col.xxx() string
function buildColStr(c) {
    const type    = (c.type || '').toUpperCase();
    const isPK    = c.pk === 1;
    const notNull = c.notnull === 1;
    const def     = c.dflt_value;

    if (isPK) return `col.id()`;

    let base;
    if      (type === 'TINYINT' || type.includes('BOOL'))           base = `col.boolean()`;
    else if (type.includes('JSON'))                                   base = `col.json()`;
    else if (type.includes('INT'))                                    base = `col.number()`;
    else if (type.includes('REAL')   || type.includes('FLOAT') ||
             type.includes('DOUBLE') || type.includes('NUMERIC') ||
             type.includes('DECIMAL'))                                base = `col.number()`;
    else                                                              base = `col.string()`;

    let chain = base;
    if (notNull && !isPK) chain += `.required()`;
    if (def !== null)     chain += `.default(${def})`;

    return chain;
}

// ─── init ─────────────────────────────────────────────────────────────────────

function cmdInit() {
    const dbDir = path.resolve(process.cwd(), 'database');
    if (!fs.existsSync(dbDir)) {
        fs.mkdirSync(dbDir, { recursive: true });
        console.log('[sutramcore] Created database/');
    }
    writeIfNotExists(path.join(dbDir, 'schema.js'),     SCHEMA_TEMPLATE);
    writeIfNotExists(path.join(dbDir, 'migrations.js'), MIGRATIONS_TEMPLATE);
    writeIfNotExists(path.join(dbDir, 'views.js'),      VIEWS_TEMPLATE);
    console.log(`
[sutramcore] ✓ Init complete

Next steps:
  1. Edit database/schema.js     — define your tables
  2. Edit database/migrations.js — add your CREATE TABLE sql
  3. In your app.js:

     const { Sutram } = require('sutramcore');

     const sewa = new Sutram({
         dbPath:     './data/app.db',
         schema:     require('./database/schema'),
         migrations: require('./database/migrations'),
         views:      require('./database/views'),
     });
`);
}

function writeIfNotExists(filePath, content) {
    const name = path.basename(filePath);
    if (fs.existsSync(filePath)) {
        console.log(`[sutramcore] Skipped ${name} (already exists)`);
        return;
    }
    fs.writeFileSync(filePath, content, 'utf8');
    console.log(`[sutramcore] Created database/${name}`);
}

